def make_plate(source: str, out_name: str, variant: str) -> None:
    prefix = source.removesuffix("_source.png")
    top = SRC / f"{prefix}_top_source.png"
    bottom = SRC / f"{prefix}_bottom_source.png"
    if top.exists() and bottom.exists():
        top_img = cover_crop(Image.open(top).convert("RGB"), (PLATE_SIZE[0], PLATE_TOP_H), anchor_y=0.5)
        bottom_img = cover_crop(Image.open(bottom).convert("RGB"), (PLATE_SIZE[0], PLATE_BOTTOM_H), anchor_y=0.5)
        img = Image.new("RGB", PLATE_SIZE, SAFE_COLOR)
        img.paste(top_img, (0, 0))
        img.paste(bottom_img, (0, PLATE_TOP_H + PLATE_SAFE_H))
        img.save(OUT / out_name)
        return
    src = Image.open(SRC / source).convert("RGB")
    img = cover_crop(src, PLATE_SIZE, anchor_y=0.5)
    img.save(OUT / out_name)


def plate_source_names(source: str) -> list[str]:
    prefix = source.removesuffix("_source.png")
    top = f"{prefix}_top_source.png"
    bottom = f"{prefix}_bottom_source.png"
    if (SRC / top).exists() and (SRC / bottom).exists():
        return [top, bottom]
    return [source]


def require_fresh_sources(names: list[str]) -> None:
    missing = [name for name in names if not (SRC / name).exists()]
    if missing:
        raise FileNotFoundError("缺少 Codex 原生图像生成源图：" + "、".join(missing))
    now = time.time()
    stale = []
    for name in names:
        path = SRC / name
        age = now - path.stat().st_mtime
        if age > MAX_SOURCE_AGE_SECONDS:
            stale.append(f"{name}（mtime={time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(path.stat().st_mtime))}）")
    if stale:
        raise RuntimeError(
            "拒绝覆盖 theme_assets：源图不是本轮新生成，可能会把旧图误当新图。"
            "请先用当前 Codex 原生图像生成能力生成新的 source 图，再运行后处理。过期源图："
            + "、".join(stale)
        )


