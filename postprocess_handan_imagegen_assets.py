def font(size: int, serif: bool = False) -> ImageFont.ImageFont:
    candidates = (
        [
            "/System/Library/Fonts/Supplemental/Songti.ttc",
            "/System/Library/Fonts/STHeiti Medium.ttc",
            "/Library/Fonts/Arial Unicode.ttf",
        ]
        if serif
        else [
            "/System/Library/Fonts/STHeiti Medium.ttc",
            "/System/Library/Fonts/Hiragino Sans GB.ttc",
            "/Library/Fonts/Arial Unicode.ttf",
        ]
    )
    for path in candidates:
        if Path(path).exists():
            return ImageFont.truetype(path, size)
    return ImageFont.load_default()


def cover_crop(img: Image.Image, size: tuple[int, int], anchor_y: float = 0.5) -> Image.Image:
    src_w, src_h = img.size
    dst_w, dst_h = size
    scale = max(dst_w / src_w, dst_h / src_h)
    resized = img.resize((round(src_w * scale), round(src_h * scale)), Image.Resampling.LANCZOS)
    x = max(0, (resized.width - dst_w) // 2)
    y = max(0, round((resized.height - dst_h) * anchor_y))
    return resized.crop((x, y, x + dst_w, y + dst_h))


def contain_blur(img: Image.Image, size: tuple[int, int]) -> Image.Image:
    bg = cover_crop(img, size).filter(ImageFilter.GaussianBlur(18))
    fg = ImageOps.contain(img, size, method=Image.Resampling.LANCZOS)
    bg.paste(fg, ((size[0] - fg.width) // 2, (size[1] - fg.height) // 2))
    return bg


def center_text(
    draw: ImageDraw.ImageDraw,
    box: tuple[int, int, int, int],
    text: str,
    fnt: ImageFont.ImageFont,
    fill: tuple[int, int, int],
    stroke_fill: tuple[int, int, int] | None = None,
    stroke_width: int = 0,
) -> None:
    bbox = draw.textbbox((0, 0), text, font=fnt, stroke_width=stroke_width)
    x = box[0] + (box[2] - box[0] - (bbox[2] - bbox[0])) / 2
    y = box[1] + (box[3] - box[1] - (bbox[3] - bbox[1])) / 2 - 4
    draw.text((x, y), text, font=fnt, fill=fill, stroke_fill=stroke_fill, stroke_width=stroke_width)


def fit_font(text: str, width: int, size: int, serif: bool = False) -> ImageFont.ImageFont:
    while size > 20:
        fnt = font(size, serif=serif)
        bbox = ImageDraw.Draw(Image.new("RGB", (10, 10))).textbbox((0, 0), text, font=fnt, stroke_width=6)
        if bbox[2] - bbox[0] <= width:
            return fnt
        size -= 2
    return font(size, serif=serif)


