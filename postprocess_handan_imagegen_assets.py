def chroma_to_alpha(img: Image.Image, key=(255, 0, 255), threshold: int = 72) -> Image.Image:
    img = img.convert("RGBA")
    px = img.load()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            dist = abs(r - key[0]) + abs(g - key[1]) + abs(b - key[2])
            if dist < threshold or (r > 170 and b > 160 and g < 120):
                px[x, y] = (r, g, b, 0)
            elif r > 140 and b > 135 and g < 145:
                px[x, y] = (r, g, b, max(0, min(a, int((dist - threshold) * 3))))
    return img


def fit_frame_to_window(frame: Image.Image, window: tuple[int, int, int, int]) -> Image.Image:
    """Use the generated full frame, but align it tightly around the story window."""
    frame = frame.convert("RGBA")
    alpha = frame.getchannel("A")
    bbox = alpha.getbbox()
    if bbox is None:
        return frame
    x, y, w, h = window
    margin_x = 112
    margin_y = 116
    target = (
        max(0, x - margin_x),
        max(0, y - margin_y),
        min(frame.width, x + w + margin_x),
        min(frame.height, y + h + margin_y),
    )
    subject = frame.crop(bbox)
    fitted = subject.resize((target[2] - target[0], target[3] - target[1]), Image.Resampling.LANCZOS)
    out = Image.new("RGBA", frame.size, (0, 0, 0, 0))
    out.alpha_composite(fitted, (target[0], target[1]))
    return out


def make_frame(source: str, out_name: str, window: tuple[int, int, int, int]) -> None:
    src = Image.open(SRC / source).convert("RGB")
    img = cover_crop(src, (1920, 1080), anchor_y=0.5)
    img = chroma_to_alpha(img)
    img = fit_frame_to_window(img, window)
    img.save(OUT / out_name)


def derive_frame_b_from_a(
    frame_a_path: Path,
    frame_b_path: Path,
    a_window: tuple[int, int, int, int],
    b_window: tuple[int, int, int, int],
) -> None:
    with Image.open(frame_a_path).convert("RGBA") as frame_a:
        ax, ay, aw, ah = a_window
        bx, by, bw, bh = b_window
        scale = min(bw / max(1, aw), bh / max(1, ah))
        scaled = frame_a.resize(
            (max(1, round(frame_a.width * scale)), max(1, round(frame_a.height * scale))),
            Image.Resampling.LANCZOS,
        )
        a_cx = ax + aw / 2
        a_cy = ay + ah / 2
        b_cx = bx + bw / 2
        b_cy = by + bh / 2
        paste_x = round(b_cx - a_cx * scale)
        paste_y = round(b_cy - a_cy * scale)
        frame_b = Image.new("RGBA", frame_a.size, (0, 0, 0, 0))
        frame_b.alpha_composite(scaled, (paste_x, paste_y))
    frame_b.paste(Image.new("RGBA", (bw, bh), (0, 0, 0, 0)), (bx, by))
    # B is a scaled derivative of A; clear tiny canvas corner guards so scaled
    # ornamentation never trips transparent-frame QA at the extreme edges.
    corner = 36
    for box in (
        (0, 0, corner, corner),
        (frame_b.width - corner, 0, frame_b.width, corner),
        (0, frame_b.height - corner, corner, frame_b.height),
        (frame_b.width - corner, frame_b.height - corner, frame_b.width, frame_b.height),
    ):
        frame_b.paste(Image.new("RGBA", (box[2] - box[0], box[3] - box[1]), (0, 0, 0, 0)), box[:2])
    frame_b.save(frame_b_path)


def qa() -> str:
    rows = []
    issues = []
    expected = {
        "main_release_plate.png": (1080, 1440),
        "library_release_plate.png": (1080, 1440),
        "main_background_16x9.png": (1920, 1080),
        "story_frame_a.png": (1920, 1080),
    }
    for name, size in expected.items():
        path = OUT / name
        with Image.open(path) as im:
            note = "ok"
            if im.size != size:
                issues.append(f"{name}: expected {size}, got {im.size}")
                note = "bad size"
            if "release_plate" in name:
                strip = im.crop((0, 360, 1080, 968)).convert("RGB")
                stat = ImageStat.Stat(strip.resize((108, 61)))
                if max(stat.stddev) > 10:
                    issues.append(f"{name}: safe strip is not clean")
                    note = "safe strip issue"
            if "story_frame" in name:
                if im.mode != "RGBA":
                    issues.append(f"{name}: not RGBA")
                    note = "not RGBA"
                alpha = im.getchannel("A")
                box = (210, 270, 1120, 782) if name.endswith("_a.png") else (356, 180, 1565, 860)
                x1, y1, x2, y2 = box
                inset_x = round((x2 - x1) * 0.16)
                inset_y = round((y2 - y1) * 0.16)
                safe_inner = alpha.crop((x1 + inset_x, y1 + inset_y, x2 - inset_x, y2 - inset_y))
                if safe_inner.getbbox() is not None:
                    issues.append(f"{name}: central keyed opening is not transparent")
                    note = "opening alpha issue"
                side_bands = {
                    "top": (x1, max(0, y1 - 120), x2, y1),
                    "bottom": (x1, y2, x2, min(im.height, y2 + 120)),
                    "left": (max(0, x1 - 120), y1, x1, y2),
                    "right": (x2, y1, min(im.width, x2 + 120), y2),
                }
                for label, side_box in side_bands.items():
                    band = alpha.crop(side_box)
                    pixels = max(1, band.width * band.height)
                    visible = sum(1 for value in band.getdata() if value > 24)
                    if visible / pixels < 0.012:
                        issues.append(f"{name}: missing or distant {label} frame side")
                        note = "incomplete frame"
                if any(alpha.getpixel(p) != 0 for p in [(0, 0), (1919, 0), (0, 1079), (1919, 1079)]):
                    issues.append(f"{name}: outer corners are not transparent")
                    note = "corner alpha issue"
            rows.append(f"- {name}: {im.size[0]}x{im.size[1]} {im.mode} {note}")
    report = "\n".join(rows) + ("\n\nAll checks passed." if not issues else "\n\nIssues:\n" + "\n".join(issues))
    (OUT / "theme_assets_qa_report.md").write_text(report, encoding="utf-8")
    return report


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    source_candidates = ["story_frame_source.png", "story_frame_a_source.png"]
    frame_source = next((name for name in source_candidates if (SRC / name).exists()), None)
    if frame_source is None:
        raise FileNotFoundError(f"缺少故事框源图，请提供其中之一：{', '.join(source_candidates)}")
    require_fresh_sources(
        plate_source_names("main_release_plate_source.png")
        + plate_source_names("library_release_plate_source.png")
        + [
            "main_background_16x9_source.png",
            frame_source,
        ]
    )
    make_plate("main_release_plate_source.png", "main_release_plate.png", "main")
    make_plate("library_release_plate_source.png", "library_release_plate.png", "library")
    make_background()
    cover_crop(Image.open(SRC / frame_source).convert("RGB"), (1920, 1080), anchor_y=0.5).save(OUT / "story_frame_source.png")
    make_frame(frame_source, "story_frame_a.png", (210, 270, 910, 512))
    print(qa())


if __name__ == "__main__":
    main()
